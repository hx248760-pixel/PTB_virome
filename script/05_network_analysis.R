# BH correction and network edge filtering.
process_correlations <- function(input_file, output_file,
                                 corr_cutoff = 0.6, fdr_cutoff = 0.05) {
  re <- read.delim(input_file, check.names = FALSE)
  re$fdr <- p.adjust(re$pvalue, method = "BH")
  re_filter <- re %>%
    filter(abs(corr) >= corr_cutoff, fdr <= fdr_cutoff)
  write.table(re_filter, output_file, quote = FALSE, sep = "\t", row.names = FALSE)
  invisible(re_filter)
}

hc_sig_re <- process_correlations(
  "results/tables/hc_re.txt",
  "results/tables/hc_sig.re"
)

tb_sig_re <- process_correlations(
  "results/tables/tb_re.txt",
  "results/tables/tb_sig.re"
)

