# Differential bacterial species.
Maaslin2(
  bacteria, metadata, "results/maaslin/bac",
  min_abundance = 0.01, min_prevalence = 0.01,
  normalization = "NONE",
  fixed_effects = c("Group", "Sex", "Age"),
  reference = c("Group,Patient"),
  plot_heatmap = TRUE, plot_scatter = TRUE
)

sig_bac <- read.delim("results/maaslin/bac/significant_results.tsv") %>%
  filter(metadata == "Group")
sig_vir <- read.delim("results/maaslin/vir/significant_results.tsv") %>%
  filter(metadata == "Group")

sig_bac_profile <- bacteria[rownames(bacteria) %in% sig_bac$feature, , drop = FALSE]
sig_vir_profile <- votu[rownames(votu) %in% sig_vir$feature, , drop = FALSE]

write.table(sig_bac_profile, "results/tables/sig_bac_spe.profile",
            quote = FALSE, sep = "\t")
write.table(sig_vir_profile, "results/tables/sig_vir_spe.profile",
            quote = FALSE, sep = "\t")

hc_list <- rownames(metadata)[metadata$Group == "Health"]
tb_list <- rownames(metadata)[metadata$Group == "Patient"]

hc_sig_vir <- sig_vir_profile[, intersect(colnames(sig_vir_profile), hc_list), drop = FALSE]
hc_sig_bac <- sig_bac_profile[, intersect(colnames(sig_bac_profile), hc_list), drop = FALSE]
tb_sig_vir <- sig_vir_profile[, intersect(colnames(sig_vir_profile), tb_list), drop = FALSE]
tb_sig_bac <- sig_bac_profile[, intersect(colnames(sig_bac_profile), tb_list), drop = FALSE]

select_occurrence <- function(x, threshold = 0.10) {
  if (ncol(x) == 0) stop("No samples available for occurrence filtering.")
  x[rowSums(x > 0) / ncol(x) > threshold, , drop = FALSE]
}

hc_selected_vir <- select_occurrence(hc_sig_vir)
hc_selected_bac <- select_occurrence(hc_sig_bac)
tb_selected_vir <- select_occurrence(tb_sig_vir)
tb_selected_bac <- select_occurrence(tb_sig_bac)

write.table(hc_selected_bac, "results/tables/hc_sig_bac.txt", quote = FALSE, sep = "\t")
write.table(hc_selected_vir, "results/tables/hc_sig_vir.txt", quote = FALSE, sep = "\t")
write.table(tb_selected_bac, "results/tables/tb_sig_bac.txt", quote = FALSE, sep = "\t")
write.table(tb_selected_vir, "results/tables/tb_sig_vir.txt", quote = FALSE, sep = "\t")

